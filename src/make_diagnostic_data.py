"""
Build a SYNTHETIC machine-downtime dataset for the Session 1 diagnostic.

NOT real factory data. It was generated by a script with a fixed random seed.
It is deliberately messy: duplicate rows, missing values, impossible values
and inconsistent text, so you have to inspect it before trusting it.

Run from the repo root:  python src/make_diagnostic_data.py
"""
import sqlite3
from pathlib import Path

import numpy as np
import pandas as pd

RAW = Path("data/raw")                  # where the CSV files go
RAW.mkdir(parents=True, exist_ok=True)  # create the folder if it is missing
rng = np.random.default_rng(42)         # fixed seed: everyone gets the same data

# ---- Table 1: machines (small lookup table) ----
machines = pd.DataFrame({
    "machine_id": [1, 2, 3, 4, 5, 6, 7, 8],
    "machine_name": ["CNC-01", "CNC-02", "CNC-03", "Press-01",
                     "Press-02", "Weld-01", "Weld-02", "Paint-01"],
    "line": ["A", "A", "A", "B", "B", "C", "C", "C"],
    "install_year": [2016, 2019, 2021, 2012, 2018, 2020, 2020, 2015],
})

# ---- Table 2: downtime events (one row per stoppage) ----
n = 320
machine_id = rng.choice(machines["machine_id"], size=n,
                        p=[.10, .12, .08, .20, .14, .12, .10, .14])

# Random start times across 2025, to the minute
offset_min = rng.integers(0, 365 * 24 * 60, size=n)
start = pd.Timestamp("2025-01-01") + pd.to_timedelta(offset_min, unit="min")

# Shift is worked out from the hour of the day
hour = start.hour
shift = np.where((hour >= 6) & (hour < 14), "Day",
         np.where((hour >= 14) & (hour < 22), "Late", "Night"))

cause = rng.choice(["Mechanical", "Electrical", "Tooling", "Operator",
                    "Material shortage"], size=n, p=[.30, .20, .25, .10, .15])

# Skewed durations (a few long stoppages); Night shift slightly longer
duration = rng.lognormal(mean=3.0, sigma=0.8, size=n)
duration = np.where(shift == "Night", duration * 1.25, duration)
duration = np.maximum(1, duration.round())

events = pd.DataFrame({
    "event_id": np.arange(1, n + 1),
    "machine_id": machine_id,
    "start_time": start.strftime("%Y-%m-%d %H:%M"),   # stored as text, like many exports
    "duration_min": duration,
    "cause": cause,
    "shift": shift,
})

# ---- Inject realistic problems (document these in your README) ----
bad = rng.choice(n, size=25, replace=False)           # inconsistent text
events.loc[bad[:10], "cause"] = events.loc[bad[:10], "cause"].str.upper()
events.loc[bad[10:20], "cause"] = events.loc[bad[10:20], "cause"].str.lower() + " "
events.loc[bad[20:], "cause"] = events.loc[bad[20:], "cause"].str.replace("Mechanical", "Mech.")
miss = rng.choice(n, size=12, replace=False)
events.loc[miss, "duration_min"] = np.nan             # missing durations
events.loc[rng.choice(n, size=2, replace=False), "duration_min"] = -5   # impossible
events.loc[rng.choice(n, size=1, replace=False), "duration_min"] = 9999 # suspicious
dupes = events.sample(6, random_state=1)              # exact duplicate rows
events = pd.concat([events, dupes]).sample(frac=1, random_state=2).reset_index(drop=True)

# ---- Save as CSV and as a SQLite database ----
machines.to_csv(RAW / "machines.csv", index=False)
events.to_csv(RAW / "downtime_events.csv", index=False)
with sqlite3.connect("data/diagnostic.db") as conn:
    machines.to_sql("machines", conn, if_exists="replace", index=False)
    events.to_sql("downtime_events", conn, if_exists="replace", index=False)

print("machines:", machines.shape, "| events:", events.shape)
